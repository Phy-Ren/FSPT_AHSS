#!/usr/bin/env python3
"""Record the explicitly named neutral E8 roots in the 3D primary source.

This is reference-side quotient data, not an E8 cochain implementation or a
calculation input. Positions refer to the SHA-pinned source used by the main
benchmark extractor; source changes require a new manual root audit.
"""
from pathlib import Path
import argparse
import hashlib
import json

# Names use catalog spelling. Each pair is spinless / physical spin-half.
ROOT_LINES = {
    "Ci": (3388, 3388), "Cs": (4566, 4566), "C2h": (4655, 4676),
    "C2v": (4843, 4902), "D2h": (4991, 5014), "S4": (5258, 5258),
    "C4h": (5374, 5403), "C4v": (5701, 5715), "D2d": (5780, 5803),
    "D4h": (5962, 5985), "C3i": (6147, 6147), "C3v": (6467, 6467),
    "D3d": (6530, 6550), "C3h": (6714, 6714), "C6h": (6822, 6843),
    "C6v": (7095, 7110), "D3h": (7258, 7280), "D6h": (7479, 7498),
    "Th": (3630, 3638), "Td": (3858, 3866), "Oh": (4268, 4279),
}


def extract(source_path, destination):
    full = json.loads((destination / "point3_full_2204.13558.json").read_text())
    digest = hashlib.sha256(source_path.read_bytes()).hexdigest()
    if digest != full["source"]["source_sha256"]:
        raise ValueError("Source hash changed; manually re-audit E8 root positions")
    lines = source_path.read_text().splitlines()
    rows = []
    for name, root_lines in ROOT_LINES.items():
        for spin, source_line in zip(("spinless", "spin_half"), root_lines):
            source_name = "S6" if name == "C3i" else name
            def plain(row):
                return row["name_as_printed"].split("=")[0].translate(str.maketrans("", "", "$_{}"))
            ref = next(r for r in full["rows"] if r["physical_spin"] == spin and plain(r) == source_name)
            root = lines[source_line - 1]
            if "E_8" not in root:
                raise ValueError(f"Missing named E8 generator at line {source_line}")
            quotient = ref["stacking_orders"].copy()
            # Removing this factor is justified by the physically specified
            # independent order-two E8 generator, not by abstract group order.
            quotient.remove(2)
            # A short description specifies a physical root without copying
            # long source prose. The exact source line remains reproducible.
            if name == "Ci":
                description = "Neutral monolayer E8 decoration on the inversion-related sigma blocks; doubling is a 3D E8 bubble."
            else:
                description = "Neutral monolayer E8 decoration on the symmetry-related 2D blocks identified in the cited root list."
            rows.append({"name": name, "physical_spin": spin,
                         "named_generator": "neutral_E8_block_decoration",
                         "generator_order": 2, "generator_description": description,
                         "source_root_line": source_line,
                         "source_table_line": ref["source_line"],
                         "full_physical_orders": ref["stacking_orders"],
                         "quotient_by_named_E8_orders": quotient,
                         "projection_meaning": "Reference group / subgroup generated by the explicitly specified independent neutral E8 root",
                         "comparison_limit": "Abstract quotient comparison; does not supply a cochain embedding or identify each solver generator with a real-space block root."})
    (destination / "point3_named_e8_quotient_2204.13558.json").write_text(json.dumps({
        "source": {**full["source"], "location": "Point-group TI root lists in main text and supplementary sections, with the per-row line references below"},
        "audit": "For each row the source identifies a neutral monolayer E8 root of order two independently of the charge/CI/root extensions. The quotient is taken by that named physical root.",
        "rows": rows}, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("/home/arxiv/2204.13558_Construction_and_classification_of_cryst/main.tex"))
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    extract(args.source, args.output)
