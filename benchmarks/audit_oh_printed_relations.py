#!/usr/bin/env python3
"""Check the Oh spinless 0D quotient of the source's explicitly printed rows.

This checks internal source arithmetic. It does not establish completeness of
physical bubble relations and does not modify calculation or benchmark inputs.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import sympy as sp
from sympy.matrices.normalforms import smith_normal_form


def audit(source):
    lines = source.read_text().splitlines()
    index = next(i for i, line in enumerate(lines) if "8n_1+6n_2+12n_3,(-1)^{n_2},+" in line)
    printed = lines[index]
    charge_part = printed.split(",")[0]
    coefficients = {int(variable): int(coefficient) for coefficient, variable
                    in re.findall(r"(\d+)n_(\d)", charge_part)}
    character_variable = int(re.search(r"\(-1\)\^\{n_(\d)\}", printed).group(1))
    if sorted(coefficients) != [1, 2, 3] or r"\mathbb{Z}_4" not in lines[index + 2]:
        raise ValueError("Source changed; re-audit the printed Oh center relations")
    atomic_relations = [[coefficients[i], int(i == character_variable), 0] for i in range(1, 4)]
    presentation = [[0, 2, 0], [0, 0, 2]] + atomic_relations
    smith = smith_normal_form(sp.Matrix(presentation), domain=sp.ZZ)
    diagonal = [abs(int(x)) for x in smith.diagonal()]
    return {"source": {"url": "https://arxiv.org/abs/2204.13558v2", "source_file": source.name,
                        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                        "location": "Oh, 0D block states, spinless paragraph; unnumbered displayed bubble subgroup",
                        "relation_line": index + 1, "claimed_quotient_line": index + 3},
            "source_relation_tex": printed.strip(),
            "source_claimed_quotient_tex": r"\mathbb{Z}_4",
            "coordinates": ["integer charge", "first reflection character mod 2", "second reflection character mod 2"],
            "printed_atomic_relations": atomic_relations,
            "presentation_including_character_periods": presentation,
            "smith_diagonal": diagonal,
            "quotient_of_printed_relations": {"torsion": [x for x in diagonal if x > 1], "freeRank": diagonal.count(0)},
            "source_claimed_quotient": {"torsion": [4], "freeRank": 0},
            "relation_subgroup_description": "Generated by (2,1,0): the displayed charge-zero rows cannot produce an independent reflection character.",
            "completeness": "The source paragraph calls the displayed family all trivial 0D states obtained by these bubbles. This audit uses exactly that family; it does not prove that every physically allowed adjoining or higher-dimensional bubble is included.",
            "conclusion": "The displayed relations imply Z4 x Z2, while the subsequent sentence claims Z4. An additional unspecified relation would be necessary to reconcile them."}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("/home/arxiv/2204.13558_Construction_and_classification_of_cryst/main.tex"))
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("point3_Oh_spinless_printed_relation_audit.json"))
    args = parser.parse_args()
    args.output.write_text(json.dumps(audit(args.source), indent=2) + "\n")
