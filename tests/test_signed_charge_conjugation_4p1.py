"""Signed global C2 classification, full source completions and incoming gauges."""
from fractions import Fraction
from itertools import product
import unittest

from insulator.signed_charge_conjugation_4p1 import C2FourData, ScalarState, ZERO


class SignedC2FourDataTests(unittest.TestCase):
    def test_H_minus_coupled_CI_square_and_shared_phase(self):
        solver = C2FourData("H_minus")
        self.assertEqual(solver.phase_source(0, 1, 0), Fraction(7, 24))
        root = solver.completions(0, 1)[0]
        self.assertEqual(root, ScalarState(0, 1, 0, Fraction(7, 48)))
        raw_square = solver.stack(root, root)
        self.assertEqual(raw_square.phase, Fraction(19, 24))
        reduced, witness = solver.canonicalize(raw_square)
        self.assertEqual(reduced, ZERO)
        self.assertEqual(witness[0]["parameters"]["u_1"], -1)
        self.assertEqual(witness[0]["phaseCorrection"], "5/24")

    def test_H_plus_integer_obstruction_and_phase_incoming(self):
        solver = C2FourData("H_plus")
        self.assertEqual(solver.integer_source(1), -1)
        self.assertEqual(solver.completions(0, 1), [])
        self.assertEqual(solver.gauge(ZERO, charge_parameter=1),
                         ScalarState(0, 0, 0, Fraction(1, 2)))
        neutral = solver.completions(1, 0)[0]
        self.assertEqual(neutral.phase, Fraction(1, 6))
        self.assertEqual(solver.canonicalize(solver.stack(neutral, neutral))[0], ZERO)

    def test_relative_AI_AII_removed_by_distinct_operations(self):
        ai, aii = C2FourData("AI_relative"), C2FourData("AII_relative")
        self.assertEqual(len(ai.completions(0, 0, 1)), 1)
        self.assertEqual(abs(ai.gauge(ZERO, n_parameter=1).charge), 1)
        self.assertEqual(ai.phase_source(0, 0, 1), 0)
        self.assertEqual(aii.phase_source(0, 0, 1), Fraction(1, 2))
        self.assertEqual(aii.completions(0, 0, 1), [])
        for solver in (ai, aii):
            self.assertEqual(solver.completions(1, 0, 0), [])
            arbitrary_phase = ScalarState(0, 0, 0, Fraction(13, 37))
            self.assertEqual(solver.canonicalize(arbitrary_phase)[0], ZERO)

    def test_complete_presentations_and_exhaustive_products(self):
        # These independent bordism targets are test expectations only; the
        # solver enumerates cochains and computes its presentation from gauges.
        targets = {"H_plus": [2], "H_minus": [2, 2, 2],
                   "AI_relative": [], "AII_relative": []}
        for name, target in targets.items():
            with self.subTest(case=name):
                result = C2FourData(name).classify()
                self.assertEqual(result["torsion"], target)
                self.assertEqual(result["freeRank"], 0)
                witness = result["witnesses"]
                self.assertEqual(len(witness["orderedProducts"]), result["preIncomingStateCount"] ** 2)
                self.assertEqual(len(witness["incomingActions"]),
                                 result["incomingGeneratorCount"] * result["preIncomingStateCount"])
                self.assertEqual(witness["checks"]["associativityChecks"], result["actualGroupOrder"] ** 3)
                self.assertEqual(witness["checks"]["fullGaugeMoveChecks"],
                                 8 * result["preIncomingStateCount"])
                self.assertFalse(result["physicalClassificationCertified"])

    def test_closed_incoming_parameter_period_and_noncanonical_sheets(self):
        for name in ("H_plus", "H_minus"):
            solver = C2FourData(name)
            for e, n in product((-2, 0, 1, 2), repeat=2):
                for state in solver.completions(e, n):
                    canonical, _ = solver.canonicalize(state)
                    self.assertIn(canonical.e, (0, 1))
                    self.assertIn(canonical.n, (0, 1))
                    # All odd signed charge gauges are generated by u3=1;
                    # even parameters are boundaries. Probe negative values too.
                    first = solver.gauge(state, charge_parameter=1)
                    for parameter in (-3, -2, 2, 3):
                        endpoint = solver.gauge(state, charge_parameter=parameter)
                        self.assertEqual(endpoint, first if parameter % 2 else state)


if __name__ == "__main__":
    unittest.main()
