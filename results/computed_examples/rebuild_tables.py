#!/usr/bin/env python3
"""Rebuild public example tables from the accepted catalog; no numerical solver."""
import argparse
import csv
from collections import Counter, defaultdict
import hashlib
import io
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def group(values):
    if not values:
        return '0'
    counts = Counter(values)
    return ' x '.join(('Z' if n == 0 else 'Z'+str(n)) + ('^'+str(c) if c>1 else '')
                      for n,c in counts.items())


def row_for(record):
    layers = {r['layer']:r['quotient_invariants'] for r in record['final_filtration']}
    result = {'case':record['id'], 'dimension':record['dimension'],
        'Gb':record.get('bosonic_group', record.get('model')),
        's_on_generators':record.get('grading_on_generators', ''),
        'crystalline_spin':record.get('crystalline_spin', ''),
        'omega2_representative':('nonzero; exact input: '+record['input_catalog']
            if record.get('omega_representative_nonzero') else '0')
            if record['symmetry_kind']=='finite_internal'
            else record['effective_internal_background']['omega2'],
        'pip':layers.get('pip',[]), 'majorana':layers.get('majorana',[]),
        'complex_fermion':layers.get('complex_fermion',[]), 'bosonic':layers.get('bosonic',[]),
        'stacking_group':record['invariant_factors'],
        'exact_input_sha256':record.get('exact_input_sha256',''),
        'result_sha256':record['sha256']}
    return result


def render(title, records, depth=0):
    rows = [row_for(r) for r in records]
    fields = list(rows[0]) if rows else ['case']
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator='\n')
    writer.writeheader()
    for r in rows:
        writer.writerow({k:json.dumps(v, separators=(',',':')) if isinstance(v,list) else v for k,v in r.items()})
    lines = ['# '+title, '', f'{len(records)} retained named calculations. Group arrays in the CSV are invariant factors.', '',
        '| Input | Dimension | Gb | Grading / crystalline spin | omega2 representative | p+ip | Majorana | CF | Bosonic | Stacking group |',
        '|---|---|---|---|---|---|---|---|---|---|']
    up = '../' * (depth+1)
    for record,row in zip(records,rows):
        if record.get('input_catalog'):
            target = up + 'inputs/' + record['id'] + '.json'
            label = f"[{record['id']}]({target})"
        else:
            label = record['id']
        sign = json.dumps(row['s_on_generators']) if isinstance(row['s_on_generators'],list) else row['crystalline_spin']
        omega = ('nonzero ([exact input]('+target+'))' if record.get('omega_representative_nonzero') else '0') \
            if record['symmetry_kind']=='finite_internal' else row['omega2_representative']
        vals = [label, str(row['dimension'])+'+1D', row['Gb'], sign, omega]
        vals += [group(row[k]) for k in ('pip','majorana','complex_fermion','bosonic','stacking_group')]
        lines.append('| '+' | '.join(str(v) for v in vals)+' |')
    lines += ['', 'The four layer columns are final filtration quotients; their direct product need not be the stacking group.',
        'Finite input links fix the full multiplication table, grading and parity-extension cocycle. A nonzero representative of omega is not by itself a claim that its cohomology class is nontrivial.',
        'For the two zero-chiral controls, the stacking column is the saved zero-chiral fiber; the catalog separately records its abstract chiral completion.', '']
    return '\n'.join(lines), stream.getvalue()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true', help='Compare generated bytes with the saved tables.')
    args = ap.parse_args()
    index = json.loads((HERE/'index.json').read_text())
    records = index['cases']
    assert index['record_count'] == len(records) == len({r['id'] for r in records})
    outputs = {}
    selected = {}
    def add(name, title, rows):
        selected[name] = len(rows)
        md, csv_text = render(title, rows, depth=name.count('/'))
        outputs['tables/'+name+'.md'] = md
        outputs['tables/'+name+'.csv'] = csv_text
    for spin, name in [('half','spin_half'),('spinless','spinless')]:
        rows = sorted((r for r in records if r['symmetry_kind']=='space_group' and r['crystalline_spin']==spin),key=lambda r:r['space_group'])
        assert len(rows) == 230
        add('space_groups_'+name, '3+1D space groups: crystalline '+('spin-1/2' if spin=='half' else 'spinless'), rows)
    rows = sorted((r for r in records if r['symmetry_kind']=='point_group'),key=lambda r:(r['point_group_index'],r['crystalline_spin']))
    assert len(rows)==64
    add('point_groups', '3+1D point groups in both crystalline spin conventions', rows)
    finite = [r for r in records if r['symmetry_kind']=='finite_internal']
    families = defaultdict(list)
    for r in finite:
        families[r['bosonic_group']].append(r)
    for dimension in (1,2,3,4):
        rows = sorted((r for r in finite if r['dimension']==dimension),key=lambda r:(r['bosonic_order'],r['bosonic_group'],r['id']))
        add(f'internal_{dimension}d', f'{dimension}+1D finite internal symmetries', rows)
    controls = [r for r in records if any('control' in c for c in r['collections'])]
    add('calibration_controls', 'Completed symmetry calibration controls', controls)
    family_links = []
    for family,rows in sorted(families.items()):
        stem = re.sub('[^A-Za-z0-9_-]','_',family)
        assert stem and 'families/'+stem not in selected
        add('families/'+stem, 'Finite internal family '+family, sorted(rows,key=lambda r:(r['dimension'],r['id'])))
        family_links.append(f'| {family} | {len(rows)} | [Markdown](families/{stem}.md) / [CSV](families/{stem}.csv) |')
    outputs['tables/families.md'] = '\n'.join(['# Finite internal families','',
        '| Family | Named calculations | Tables |','|---|---:|---|',*family_links,''])
    pending = json.loads((HERE/'pending.json').read_text())['cases']
    outputs['PENDING.md'] = '\n'.join(['# Pending inputs','',
        'These exact inputs are planned calculations awaiting complete acceptance. No stacking group is asserted here.','',
        *[f"- [{r['id']}](inputs/{r['id']}.json), {r['dimension']}+1D." for r in pending],''])
    for name,content in outputs.items():
        target = HERE/name
        if args.check:
            assert target.read_text()==content, name
        else:
            target.parent.mkdir(parents=True,exist_ok=True)
            target.write_text(content)
    # Parse every CSV back and check every group-valued cell against the catalog.
    by_id = {r['id']:row_for(r) for r in records}
    cells = 0
    background_cells = 0
    for name, content in outputs.items():
        if not name.endswith('.csv'):
            continue
        for row in csv.DictReader(io.StringIO(content)):
            expected = by_id[row['case']]
            assert row['omega2_representative']==expected['omega2_representative'], (name,row['case'],'omega2_representative')
            background_cells += 1
            for key in ('pip','majorana','complex_fermion','bosonic','stacking_group'):
                assert json.loads(row[key]) == expected[key], (name,row['case'],key)
                cells += 1
    print(json.dumps({'status':'passed','mode':'check' if args.check else 'write',
        'record_count':len(records),'generated_table_files':len(outputs),
        'verified_csv_group_cells':cells,'verified_omega_representative_cells':background_cells,
        'numerical_science_executed':False},sort_keys=True))


if __name__=='__main__':
    main()
