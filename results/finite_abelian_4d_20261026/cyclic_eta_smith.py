#!/usr/bin/env python3
"""Exact cyclic Spin--Z_(2m) classification from Hsieh's eta characters.

This is a cyclic-group calculation, not a proposed formula for a product of
cyclic groups.  The latter can have bordism classes invisible to free fermions.

Reference: arXiv:1808.02881, equations labelled anomaly_twisted and
iso_Im_cyclic_2 in the downloaded source.  The paper proves eta completeness
for these cyclic groups by matching an independent bordism upper bound.
"""

from argparse import ArgumentParser
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import hermite_normal_form, smith_normal_form


def eta_presentation(m: int):
    """Return an integral 2-generator presentation and invariant factors.

    All odd charges q modulo 2m are included.  Their two eta values lie in
    (Z/D)^2 with D=48m.  If H is a basis for the lattice generated by their
    numerators and D Z^2, their image is H Z^2 / D Z^2.  Thus H^(-1)D I is
    an exact integral relation matrix, with no AHSS extension left open.
    """
    if m < 1:
        raise ValueError("m must be a positive integer")
    denominator = 48 * m
    columns = [[denominator, 0], [0, denominator]]
    for q in range(1, 2 * m, 2):
        columns.append([
            ((2*m*m + m + 1)*q**3 - (m + 3)*q) % denominator,
            (24*(m*q**3 + q)) % denominator,
        ])
    numerator_lattice = hermite_normal_form(Matrix.hstack(*(Matrix(c) for c in columns)))
    relations = numerator_lattice.inv() * denominator * Matrix.eye(2)
    if any(x.q != 1 for x in relations):
        raise AssertionError("The relation matrix must be integral")
    diagonal = smith_normal_form(relations, domain=ZZ)
    factors = [abs(int(diagonal[i, i])) for i in range(2) if abs(diagonal[i, i]) > 1]
    return relations, factors


def closed_factors(m: int):
    """The proven cyclic formula, sorted by divisibility."""
    if m % 2:
        # Odd m splits the fermion parity factor from C_m.
        factors = [m, m] if m % 3 else [m // 3, 3*m]
    else:
        factors = [m // 2, 8*m] if m % 3 else [m // 6, 24*m]
    return [x for x in factors if x > 1]


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("m", type=int, nargs="*")
    parser.add_argument("--check-through", type=int, default=0)
    args = parser.parse_args()
    if args.check_through:
        for m in range(1, args.check_through + 1):
            _, obtained = eta_presentation(m)
            expected = closed_factors(m)
            assert obtained == expected, (m, obtained, expected)
        print(f"Exact eta/Smith checks passed for 1 <= m <= {args.check_through}.")
    for m in args.m:
        presentation, factors = eta_presentation(m)
        print(f"m={m}; G_f=C_{2*m}^f; presentation={presentation.tolist()}; factors={factors}")


if __name__ == "__main__":
    main()
